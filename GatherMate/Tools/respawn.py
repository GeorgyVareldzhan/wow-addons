#!/usr/bin/env python3
"""Build GatherMate/Respawn.lua from the Sirus knowledge base cache.

Reads vein objects cached by CraftPlan/Tools/sirusdb.py (object_<id>.json)
and writes, per vein name and zone, the most common respawn time plus the
points whose respawn differs from it.

Usage: python3 Tools/respawn.py          # build from cache only, no network
       python3 Tools/respawn.py --fetch  # first fetch veins of the ores below (polite, cached)
"""
import collections
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.dirname(HERE)
CACHE = os.path.join(ADDON, "..", "CraftPlan", "Tools", ".cache")
OUT = os.path.join(ADDON, "Respawn.lua")

# ores whose veins CraftPlan does not fetch (itemID, comment); checked by the name on the page
EXTRA_ORES = [
    (2775, "silver"), (2776, "gold"), (7911, "truesilver"), (11370, "dark iron"),
    (3340, "incendicite"), (5833, "indurium"), (4278, "lesser bloodstone"),
    (23426, "khorium"), (23427, "eternium"), (32464, "nethercite"),
]

# Sirus name -> name GatherMate's ruRU locale uses for the same node
ALIAS = {
    "Огневитовая жила": "Ароматитовая жила",
    "Покрытая слизью серебряная жила": "Покрытая слизью серебрянная жила",
}


def fetch():
    sys.path.insert(0, os.path.dirname(CACHE))
    import sirusdb
    fx = sirusdb.Fetcher(delay=4, refresh=False)
    prog = sirusdb.Progress("veins")
    objs = []
    for item, note in EXTRA_ORES:
        d = fx.get(item, prog)
        name = (d.get("item") or {}).get("name", "?")
        rows = (sirusdb.tab(d, "mined_from_object") or {}).get("items", [])
        print("  %d %s (%s): %d жил" % (item, name, note, len(rows)), file=sys.stderr)
        objs += [r["entry"] for r in rows if r["entry"] not in objs]
    prog.total = len(objs)
    for obj in objs:
        fx.get(obj, prog, kind="object")
        prog.done += 1
    prog.finish("запросов %d, из кеша %d" % (fx.requests, fx.cached))


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    zones = {}
    spawns = collections.defaultdict(list)  # (name, areaId) -> [spawn]
    for f in sorted(glob.glob(os.path.join(CACHE, "object_*.json"))):
        with open(f, encoding="utf-8") as fh:
            o = json.load(fh)["object"]
        for loc in o.get("locations") or []:
            zones[loc["zone_id"]] = loc["name"]
        for s in o.get("spawns") or []:
            if s.get("respawn"):
                spawns[(ALIAS.get(o["name"], o["name"]), s["areaId"])].append(s)

    veins = collections.defaultdict(dict)  # name -> zone -> (mode, [exceptions])
    total = collections.defaultdict(collections.Counter)
    for (name, area), sp in spawns.items():
        zone = zones.get(area)
        if not zone:
            continue
        cnt = collections.Counter(s["respawn"] for s in sp)
        total[name].update(cnt)
        mode = cnt.most_common(1)[0][0]
        exc = [(s["posX"], s["posY"], s["respawn"]) for s in sp if s["respawn"] != mode]
        veins[name][zone] = (mode, sorted(exc))

    lines = [
        "-- Generated by Tools/respawn.py from the Sirus knowledge base. Do not edit.",
        "-- [vein] = { [\"*\"] = seconds, [zone] = { seconds, {x%, y%, seconds}, ... } }",
        "GatherMate_Respawn = {",
    ]
    for name in sorted(veins):
        lines.append("\t[%s] = {" % lua_str(name))
        lines.append('\t\t["*"] = %d,' % total[name].most_common(1)[0][0])
        for zone in sorted(veins[name]):
            mode, exc = veins[name][zone]
            parts = [str(mode)] + ["{%g,%g,%d}" % e for e in exc]
            lines.append("\t\t[%s] = {%s}," % (lua_str(zone), ", ".join(parts)))
        lines.append("\t},")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("%s: %d veins, %d zones" % (OUT, len(veins), sum(len(v) for v in veins.values())))


if __name__ == "__main__":
    if "--fetch" in sys.argv[1:]:
        fetch()
    main()
