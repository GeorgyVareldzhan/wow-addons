#!/usr/bin/env python3
"""Build Data/TrainerData.lua: profession trainers (NPC ids and faction) from the Questie database.

Reads Questie-335/Database/{Classic,TBC,Wotlk}/*NpcDB.lua (later expansions override earlier ones) and takes
NPCs whose title is "<Profession> Trainer", optionally prefixed with a rank (Journeyman/Expert/Artisan/Master/
Grand Master). Specialization trainers (Weaponsmith, Goblin Engineering, ...) are left out. No network.

Usage: python3 Tools/trainers.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.dirname(HERE)
QDB = os.path.join(ADDON, "..", "Questie-335", "Database")
OUT = os.path.join(ADDON, "Data", "TrainerData.lua")
FILES = ["Classic/classicNpcDB.lua", "TBC/tbcNpcDB.lua", "Wotlk/wotlkNpcDB.lua"]

PROF = {  # English title word -> skill id
    "Blacksmithing": 164, "Leatherworking": 165, "Alchemy": 171, "Cooking": 185, "Mining": 186,
    "Tailoring": 197, "Engineering": 202, "Enchanting": 333, "Jewelcrafting": 755, "Inscription": 773,
    "First Aid": 129,
}
TITLE = re.compile(r'^(?:(?:Journeyman|Expert|Artisan|Master|Grand Master) )?(' + "|".join(PROF) + r') Trainer$')
ROW = re.compile(r'^\[(\d+)\] = \{(.*)\},?\s*$', re.M)
FIELD = re.compile(r'"((?:[^"\\]|\\.)*)"|nil')


def main():
    found = {}
    for rel in FILES:
        with open(os.path.join(QDB, rel), encoding="utf-8", errors="replace") as fh:
            text = fh.read()
        for m in ROW.finditer(text):
            npc, body = int(m.group(1)), m.group(2)
            # the faction ("A", "H", "AH" or nil) comes right before the title, the title is the last string
            tail = re.search(r',("A"|"H"|"AH"|nil),"([^"]*)",[^,"]*$', body)
            if not tail:
                continue
            t = TITLE.match(tail.group(2))
            if t:
                found[npc] = (PROF[t.group(1)], tail.group(1).strip('"') if tail.group(1) != "nil" else "")
            elif npc in found:
                del found[npc]  # a later expansion changed the title
    by = {}
    for npc, (sk, fac) in sorted(found.items()):
        by.setdefault(sk, []).append((npc, fac))
    lines = ["-- Generated by Tools/trainers.py from the Questie database. Do not edit.",
             "-- [skill id] = { npc, \"A\"|\"H\"|\"AH\"|\"\", npc, faction, ... }",
             "CraftPlan_Trainers = {"]
    for sk in sorted(by):
        flat = ", ".join('%d, "%s"' % e for e in by[sk])
        lines.append("\t[%d] = { %s }," % (sk, flat))
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("%s: %s" % (OUT, ", ".join("%d: %d" % (sk, len(v)) for sk, v in sorted(by.items()))))


if __name__ == "__main__":
    main()
