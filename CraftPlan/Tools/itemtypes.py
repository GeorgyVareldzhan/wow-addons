#!/usr/bin/env python3
"""Build Data/ItemTypes.lua: class, subclass and equip slot of every recipe product (Data/Recipes.lua),
plus localized subclass names - from the client tables (DBFilesClient\\Item.dbc, ItemSubClass.dbc) via mpq.py.
The game knows an item only after it was seen (GetItemInfo), this table always does.

Items of Sirus itself are not in the client tables: they are taken from the Sirus knowledge base cache
(Tools/.cache/<id>.json, sirusdb.py). --fetch 164,755 first downloads the missing ones of these professions
(politely, one at a time, cached).

Usage: python3 -I Tools/itemtypes.py [--fetch <skill ids>]
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import dbc  # noqa: E402
import mpq  # noqa: E402

ADDON = os.path.dirname(HERE)
DATA = os.path.join(ADDON, "..", "..", "..", "Data")
OUT = os.path.join(ADDON, "Data", "ItemTypes.lua")
RU = 8  # ruRU column of the localized strings


def archives():
    fs = glob.glob(os.path.join(DATA, "*.[mM][pP][qQ]")) + glob.glob(os.path.join(DATA, "ruRU", "*.mpq"))

    def key(p):  # later patches win, locale patches over base ones
        b = os.path.basename(p).lower()
        suf = b.replace("patch-ruru", "").replace("patch", "").replace(".mpq", "").strip("-")
        return (b.startswith("patch"), "ruru" in b, suf != "", suf)
    return sorted(fs, key=key, reverse=True)


def read(name):
    for p in archives():
        try:
            d = mpq.Archive(p).read(name)
        except Exception:
            d = None
        if d:
            return d
    raise SystemExit("нет " + name)


def main():
    src = open(os.path.join(ADDON, "Data", "Recipes.lua"), encoding="utf-8").read()
    want, by_sk, sk = set(), {}, None
    for line in src.splitlines():
        m = re.match(r"\s*\[(\d+)\] = \{", line)
        if m:
            sk = int(m.group(1))
            continue
        m = re.match(r'\s*"\d+\|[^|"]*\|\d+\|\d+\|\d+\|(\d+)\|', line)
        if m and int(m.group(1)):
            want.add(int(m.group(1)))
            by_sk.setdefault(sk, set()).add(int(m.group(1)))
    rows, _ = dbc.parse(read("DBFilesClient\\Item.dbc"))
    items = {r[0]: (r[1], r[2], r[6]) for r in rows if r[0] in want}
    import sirusdb
    fx = sirusdb.Fetcher(delay=4, refresh=False)
    if "--fetch" in sys.argv:
        sks = {int(x) for x in sys.argv[sys.argv.index("--fetch") + 1].split(",")}
        todo = sorted(i for s in sks for i in by_sk.get(s, ()) if i not in items and not fx.is_cached(i))
        prog = sirusdb.Progress("предметы")
        prog.total = len(todo)
        gone = []
        for i in todo:
            try:
                fx.get(i, prog)
            except SystemExit as e:
                if "HTTP 404" not in str(e):
                    raise
                gone.append(i)  # not in the base: GetItemInfo in game is all there is
            prog.done += 1
        if gone:
            print("нет в базе: %s" % ", ".join(map(str, gone)), file=sys.stderr)
        prog.finish("запросов %d" % fx.requests)
    api = 0
    for i in want - set(items):
        if fx.is_cached(i):
            it = (fx.get(i, None) or {}).get("item") or {}
            if it.get("class") is not None:
                items[i] = (it["class"], it["subclass"], it.get("inventory_type") or 0)
                api += 1
    subs, st = dbc.parse(read("DBFilesClient\\ItemSubClass.dbc"))
    used = {(c, s) for c, s, _ in items.values()}
    names = {}
    for r in subs:
        if (r[0], r[1]) in used:
            verbose, display = dbc.string(st, r[27 + RU]), dbc.string(st, r[10 + RU])
            names[(r[0], r[1])] = verbose or display
    out = ["-- Generated by Tools/itemtypes.py from the client tables (Item.dbc, ItemSubClass.dbc). Do not edit.",
           "-- [item] = class * 10000 + subclass * 100 + equip slot (InventoryType)",
           "CraftPlanItemType = {"]
    for i in sorted(items):
        c, s, inv = items[i]
        out.append("\t[%d] = %d," % (i, c * 10000 + s * 100 + inv))
    out.append("}")
    out.append("-- [class * 100 + subclass] = name, as the profession window headers write it")
    out.append("CraftPlanSubName = {")
    for (c, s) in sorted(names):
        out.append('\t[%d] = "%s",' % (c * 100 + s, names[(c, s)].replace('"', '\\"')))
    out.append("}")
    open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("предметов %d из %d (из базы Sirus %d), подтипов %d" % (len(items), len(want), api, len(names)), file=sys.stderr)


main()
